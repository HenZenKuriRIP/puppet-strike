import { chromium } from 'playwright-core';
const exe = process.env.HOME + '/.cache/ms-playwright/chromium-1140/chrome-linux/chrome';
const b = await chromium.launch({ executablePath: exe, args: ['--use-gl=angle', '--use-angle=swiftshader', '--enable-unsafe-swiftshader'] });
const p = await b.newPage({ viewport: { width: 1280, height: 720 } });
const errs = []; p.on('pageerror', (e) => errs.push(e.message)); p.on('console', (m) => m.type() === 'error' && errs.push(m.text()));
const S = (n) => p.screenshot({ path: `../screenshots/m4-${n}.png` });
const ev = (f, a) => p.evaluate(f, a);
const W = (ms) => p.waitForTimeout(ms);
const until = async (f, ms = 20000) => { const t = Date.now(); while (Date.now() - t < ms) { if (await ev(f)) return true; await W(200); } return false; };
const unpause = () => ev(() => { const u = window.__ps.useUI.getState(); if (u.phase === 'paused') u.set({ phase: 'playing' }); });
const r = {};
await p.goto('http://localhost:4173'); await W(4000);
await ev(() => window.__ps.useUI.getState().setSettings({ quality: 'low' })); await W(1500);
await S('menu');
await p.click('#btn-chars'); await W(1200); await S('characters-locks');
r.lockedCount = await ev(() => document.querySelectorAll('.locked').length);
await p.click('#btn-back'); await W(300);
await p.click('#btn-settings'); await W(300); await p.click('#btn-reset-save'); await W(200); await S('settings-reset'); await p.click('#btn-reset-confirm'); await W(200); await p.click('#btn-settings'); await W(200);
await p.click('#btn-play'); await W(500); await S('play-modes');
// --- Survival
await p.click('#mode-survival'); await W(2000); await unpause();
await ev(() => { const w = window.__ps.world; w.player.hp = 9999; });
await W(2500); await S('survival');
await ev(() => window.__ps.runFlow.requestUpgrade('wave')); await until(() => window.__ps.useUI.getState().phase === 'upgrade'); await W(900); await S('survival-upgrade');
r.choices = await ev(() => [...document.querySelectorAll('[id^=upg-]')].map((e) => e.textContent.slice(0, 40)));
await p.click('#upg-0'); await W(500); await unpause();
r.afterPick = await ev(() => ({ phase: window.__ps.useUI.getState().phase, stacks: JSON.stringify(window.__ps.world.run.stacks ?? window.__ps.world.run) .slice(0, 200) }));
await ev(() => { const { world: w } = window.__ps; w.player.hp = 0; w.player.dead = true; w.outcome = 'lost'; });
r.survivalResults = await until(() => !!document.querySelector('#results'), 15000); await W(800); await S('survival-results');
// --- Adventure
await p.click('#btn-menu'); await W(500);
await p.click('#btn-play'); await W(400); await p.click('#mode-adventure'); await W(500); await S('adventure-map');
r.stage2LockedAtStart = await ev(() => document.querySelector('#stage-2')?.disabled ?? null);
await p.click('#stage-1'); await W(2500); await unpause(); await ev(() => { window.__ps.world.player.hp = 9999; }); await W(2500); await S('adventure-stage1');
await ev(() => window.__ps.runFlow.stageCleared());
r.stageUpgrade = await until(() => window.__ps.useUI.getState().phase === 'upgrade'); await W(900); await S('stage-upgrade');
await p.click('#upg-1'); await W(2500); await unpause();
r.stageNow = await ev(() => window.__ps.world.run.stage);
await ev(() => window.__ps.runFlow.beginStage(3)); await W(300); await unpause();
await ev(() => { window.__ps.world.player.hp = 99999; window.__ps.world.player.maxHp = 99999; });
await W(1500); await S('boss-intro');
await until(() => window.__ps.world.boss.s.intro <= 0, 30000); await W(5000); await ev(() => { window.__ps.world.player.hp = 99999; }); await S('boss-phase1');
const setHp = (f) => ev((f) => { const w = window.__ps.world; const k = w.enemies.items.find((e) => e.active && e.type === "king"); k.hp = k.maxHp * f; w.player.hp = 99999; }, f);
await setHp(0.55); r.p2 = await until(() => window.__ps.world.boss.s.phase === 2); await W(1500); await S('boss-phase2-transition');
await until(() => window.__ps.world.boss.s.transition <= 0); await W(5000); await ev(() => { window.__ps.world.player.hp = 99999; }); await S('boss-phase2');
await setHp(0.2); r.p3 = await until(() => window.__ps.world.boss.s.phase === 3); await until(() => window.__ps.world.boss.s.transition <= 0); await W(6000); await ev(() => { window.__ps.world.player.hp = 99999; }); await S('boss-phase3');
r.hazards = await ev(() => JSON.stringify(window.__ps.world.hazards).length);
r.bossBar = await ev(() => !!document.querySelector('#boss-bar'));
await ev(() => { const w = window.__ps.world; const k = w.enemies.items.find((e) => e.active && e.type === 'king'); window.__ps.damageEnemy(k, k.hp + 10); }); r.defeated = await until(() => window.__ps.world.boss.s.defeated); await W(1200); await S('boss-defeat');
r.advResults = await until(() => !!document.querySelector('#results'), 30000); await W(1000); await S('results');
r.save = await ev(() => Object.fromEntries(Object.keys(localStorage).map((k) => [k, localStorage[k].slice(0, 300)])));
r.errors = errs.slice(0, 10);
console.log(JSON.stringify(r, null, 1));
await b.close();
